test("every mass the server emits is a whole number of grams", async (t) => {
  const { c } = open(t);
  await c.init();
  const id = await seed(c);
  const r = await c.json("carton_report", { packing_list: id, divisor: 6000 });
  for (const cn of r.cartons) {
    for (const k of ["tare_grams", "net_grams", "gross_grams"]) {
      assert.ok(Number.isInteger(cn[k]), `${cn.id}.${k} is not an integer: ${cn[k]}`);
    }
    assert.ok(cn.volumetric_grams === null || Number.isInteger(cn.volumetric_grams), `${cn.id}.volumetric_grams`);
    assert.ok(cn.chargeable_grams === null || Number.isInteger(cn.chargeable_grams), `${cn.id}.chargeable_grams`);
    assert.equal(cn.gross_grams, cn.tare_grams + cn.net_grams, `${cn.id}: tare plus net does not make the gross`);
    if (cn.chargeable_grams !== null) assert.equal(cn.chargeable_grams, Math.max(cn.gross_grams, cn.volumetric_grams));
  }
  assert.equal(r.totals.gross_grams, r.cartons.reduce((n, x) => n + x.gross_grams, 0), "the shipment gross is not the sum of the cartons");
  assert.equal(r.totals.tare_grams + r.totals.net_grams, r.totals.gross_grams);
  const shortfallRows = (await c.json("packing_shortfall", { packing_list: id })).rows;
  for (const row of shortfallRows) {
    assert.ok(Number.isInteger(row.expected) && Number.isInteger(row.packed) && Number.isInteger(row.outstanding), JSON.stringify(row));
    assert.equal(row.outstanding, row.expected - row.packed, "outstanding is not expected minus packed");
  }
  const listed = await c.json("packing_list_list", { reference: REFERENCE });
  assert.equal(listed.packing_lists.length, 1);
});

