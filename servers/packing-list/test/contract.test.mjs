test("the free tier is the documented one: everything but writing the slip to a file", async (t) => {
  const { c } = open(t);
  await c.init();
  const id = await seed(c);
  for (const [tool, args] of [
    ["packing_list_show", { packing_list: id }],
    ["packing_list_list", {}],
    ["carton_report", { packing_list: id }],
    ["packing_shortfall", { packing_list: id }],
    ["packing_slip", { packing_list: id }],
    ["packing_expect", { packing_list: id, description: "Spare shelf", quantity: 1 }],
    ["carton_add", { packing_list: id, label: "Box 3", tare_grams: 100 }],
    ["pack_item", { packing_list: id, carton: "C03", description: "Spare shelf", quantity: 1, unit_grams: 1250 }],
    ["unpack_item", { packing_list: id, line: "L05" }],
    ["packing_list_status", { packing_list: id, status: "cancelled" }],
    ["packing_list_delete", { packing_list: id, confirm: true }],
  ]) {
    const r = await c.call(tool, args);
    assert.equal(r.isError, false, `${tool} was gated: ${r.text}`);
  }
  const fresh = await c.json("packing_list_create", { reference: "PO-7", consignee: "Harbour Cafe" });
  const gated = await c.call("packing_slip", { packing_list: fresh.created.id, out_path: "/tmp/should-not-be-written.txt" });
  assert.equal(gated.isError, true, "packing_slip wrote a file on the free tier");
  assert.match(gated.text, /Pro is a one-time \$\d+ for this server/);
  assert.match(gated.text, /license_activate/);
  // The conversion instrument: every gate link carries the tool that tripped it.
  assert.match(gated.text, new RegExp(`src=${PRODUCT}\\.packing_slip`), "the gate link is untagged");
  assert.match(gated.text, /any total or journal composed outside them is an estimate/, "the NO_HAND_MATH sentence is missing");
  assert.match(gated.text, new RegExp(`Or all \\d+ servers for \\$\\d+: https://mcp\\.zovo\\.one/buy/bundle\\?src=${PRODUCT}\\.packing_slip\\.bundle$`), "the bundle sentence is missing");
  assert.equal(existsSync("/tmp/should-not-be-written.txt"), false, "the gate wrote a file before refusing");
});

