test("every amount the server emits is an integer number of minor units", async (t) => {
  const { c } = open(t, { key: proKey() });
  await c.init();
  await seed(c);
  const got = await c.json("sku_get", { sku: "WEB-AUDIT", date: RESOLVE_DATE });
  assert.ok(Number.isInteger(got.price_minor), `price_minor is not an integer: ${got.price_minor}`);
  const r = await c.json("lines_resolve", { lines: LINES, date: RESOLVE_DATE });
  for (const l of r.lines) {
    assert.ok(Number.isInteger(l.unit_price_minor), JSON.stringify(l));
    assert.ok(Number.isInteger(l.value_minor), JSON.stringify(l));
  }
  for (const k of ["subtotal_minor", "net_minor", "vat_minor", "total_minor"]) {
    assert.ok(Number.isInteger(r.totals[k]), `${k} is not an integer: ${r.totals[k]}`);
  }
  assert.equal(r.totals.net_minor + r.totals.vat_minor, r.totals.total_minor, "net plus VAT does not make the total");
  for (const i of r.quote_create.arguments.items) {
    assert.ok(Number.isInteger(i.unit_price_minor), `quote_create takes MINOR units and got ${i.unit_price_minor}`);
  }
});
