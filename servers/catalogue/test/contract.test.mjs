test("this server writes its own directory and no sibling store, on any tool", async (t) => {
  const { box, c } = open(t, { key: proKey() });
  await c.init();
  await seed(c);
  await c.call("lines_resolve", { lines: LINES, client: "Harbour Cafe", date: RESOLVE_DATE });
  await c.call("price_list_text", {});
  await c.call("price_list_pdf", { date: RESOLVE_DATE });
  await c.call("catalogue_report", {});
  await c.call("sku_set", { sku: "GONE", name: "Temporary", unit: "each", price_minor: 100, valid_from: "2026-01-01" });
  await c.call("sku_delete", { sku: "GONE" });

  const files = readdirSync(storeDir(box.dataHome)).filter((f) => !f.startsWith("."));
  assert.deepEqual(files.sort(), ["counter.json", "pdf", "rates.json", "register.json", "skus.json"]);
  // The shared profile was READ and must be untouched: one file, the one the test wrote.
  const siblings = readdirSync(join(box.dataHome, "mcp-servers")).sort();
  assert.deepEqual(siblings, ["catalogue", "profile"], `a sibling store was created: ${siblings.join(", ")}`);
  assert.deepEqual(readdirSync(join(box.dataHome, "mcp-servers", "profile")), ["business.json"],
    "this server wrote into the shared profile directory; it must only read business.json");
});

test("no price is derived and stored: a SKU record holds its rows and nothing worked out from them", async (t) => {
  const { box, c } = open(t, { key: proKey() });
  await c.init();
  await seed(c);
  await c.call("lines_resolve", { lines: LINES, date: RESOLVE_DATE });
  const raw = readFileSync(join(storeDir(box.dataHome), "skus.json"), "utf8");
  // A derived figure stored under any of these keys is a second copy of what the rows say.
  for (const key of ["price_minor", "current_price", "in_force", "net_minor", "total_minor",
    "vat_minor", "value_minor", "unit_price", "unit_price_minor"]) {
    assert.equal(raw.includes(`"${key}"`), false, `${key} was stored; every price must be derived on the call`);
  }
  const stored = JSON.parse(raw).find((s) => s.sku === "WEB-AUDIT");
  assert.deepEqual(Object.keys(stored).sort(), ["created", "name", "prices", "sku", "unit", "updated", "vat_rate"]);
  assert.deepEqual(Object.keys(stored.prices[0]).sort(), ["amount_minor", "created", "currency", "tier", "valid_from"]);
  assert.equal(stored.prices.length, 3, "the ladder must survive on disk as three rows");
});

test("the money engine is the invoice server's own, not a copy", async () => {
  // If servers/invoice changes its rounding basis, this server must change with it, which
  // it does because it never implements the arithmetic: it imports it.
  const engine = readFileSync(join(HERE, "src", "catalogue.ts"), "utf8");
  assert.match(engine, /import \{[^}]*computeTotals[^}]*\} from "@theluckystrike\/mcp-invoice\/lib";/,
    "the totals must come from the invoice server, never be restated here");
  assert.match(engine, /roundHalfUp/, "the rounding must be the invoice server's roundHalfUp");
  for (const forbidden of [/function roundHalfUp/, /function computeTotals/, /Math\.round\(/]) {
    assert.equal(forbidden.test(engine), false, `src/catalogue.ts reimplements ${forbidden}`);
  }
  const index = readFileSync(join(HERE, "src", "index.ts"), "utf8");
  assert.match(index, /import \{ renderDocPdf \} from "@theluckystrike\/mcp-billing-docs\/lib";/,
    "the A4 renderer must be imported from billing-docs, never reproduced here");
  assert.match(index, /readSharedProfile/, "the default currency must come from the shared business profile");
});

test("src holds no network call and no stdout write", async () => {
  // grep exits 1 on no match, which is the passing case here.
  let raw = "";
  try {
    raw = execFileSync("grep", ["-rEn", "fetch\\(|https?://|node:http|node:net|node:dns|console\\.", join(HERE, "src")], { encoding: "utf8" });
  } catch (e) {
    if (e.status !== 1) throw e;
  }
  const out = raw.trim().split("\n").filter(Boolean);
  const offending = out.filter((l) => !/mcp\.zovo\.one|github\.com|modelcontextprotocol\.io/.test(l));
  assert.deepEqual(offending, [], `network or stdout in src:\n${offending.join("\n")}`);
});

