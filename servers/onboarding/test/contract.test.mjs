test("the free tier is the documented one: everything free except multi-hire apply and the CSV export", async (t) => {
  const { c } = open(t);
  await c.init();
  const hire = await seedHire(c);
  assert.ok(hire.id, "adding a hire is free");
  for (const task of TASKS) {
    const r = await c.call("onboarding_task_add", { hire: hire.id, ...task });
    assert.equal(r.isError, false, "adding a task is free");
  }
  const apply = await c.call("onboarding_template_apply", { hire: hire.id, tasks: TASKS });
  assert.equal(apply.isError, false, "applying to one hire is free");

  const second = await seedHire(c, "Grace Hopper", "engineer", "2099-02-02");
  const multi = await c.call("onboarding_template_apply", { hire: [hire.id, second.id].join(",") });
  assert.equal(multi.isError, true, "applying to two hires at once is Pro");
  assert.match(multi.text, /is Pro\./);
  assert.match(multi.text, /mcp\.zovo\.one\/buy\/onboarding/, "the cap message carries the tagged buy link");
  assert.match(multi.text, /license_activate/, "the cap message names the activation tool");
});

