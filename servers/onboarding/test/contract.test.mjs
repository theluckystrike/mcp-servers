// Contract suite for onboarding. Mechanical assertions only.
//
// Ported from the checklist contract suite onto this server's facts: one version across
// package.json, src/version.ts, serverInfo and the three registry manifests; JSON-RPC-only
// stdout; tool-description hygiene; the free/Pro tier switch (multi-hire apply and the
// CSV export); that nothing outside this server's own directory is written; the snapshot
// rule (a hire copies its template's tasks at apply); and the estate registration.
// It never asserts a number a human chose; those live in test/unit.test.mjs.
import { test } from "node:test";
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync, rmSync, readdirSync } from "node:fs";
import { join } from "node:path";
import { client, sandbox, cleanup, proKey, storeDir, seedHire, REPO, TASKS } from "./_client.mjs";

const HERE = join(REPO, "servers", "onboarding");
const PRODUCT = "onboarding";
const MAX_DESCRIPTION = 220;
const HARD_MAX_DESCRIPTION = 1200;
const MANIFESTS = ["server.json", "server.mcpb.json", "server.onboarding.json"];
const OVER_LENGTH_BASELINE = ["onboarding_hire_add", "onboarding_template_apply"];

function open(t, opts = {}) {
  const box = sandbox();
  const c = client({ dataHome: box.dataHome, ...opts });
  t.after(() => { c.close(); cleanup(box.dir); });
  return { box, c };
}

test("the version is one number: package.json, src/version.ts, serverInfo and every manifest agree", async (t) => {
  const pkg = JSON.parse(readFileSync(join(HERE, "package.json"), "utf8"));
  assert.equal(pkg.name, "@theluckystrike/mcp-onboarding");
  assert.match(pkg.version, /^\d+\.\d+\.\d+$/, "package version must be a plain semver");
  assert.ok(pkg.description.length < 100, `package description is ${pkg.description.length} chars`);
  const generated = readFileSync(join(HERE, "src", "version.ts"), "utf8");
  assert.match(generated, /GENERATED by scripts\/sync-versions\.mjs/, "version.ts must be generated, not hand written");
  assert.match(generated, new RegExp(`export const VERSION = "${pkg.version.replace(/\./g, "\\.")}";`),
    `src/version.ts does not carry ${pkg.version}; run node scripts/sync-versions.mjs`);

  const { c } = open(t);
  const info = await c.init();
  assert.equal(info.serverInfo.version, pkg.version, "serverInfo.version must equal the package version");
  assert.equal(info.serverInfo.name, "mcp-onboarding");

  for (const file of MANIFESTS) {
    const j = JSON.parse(readFileSync(join(HERE, file), "utf8"));
    assert.equal(j.version, pkg.version, `${file} version`);
    for (const p of j.packages ?? []) {
      assert.equal(p.version, pkg.version, `${file} package entry version`);
      assert.equal(p.transport.type, "stdio", `${file} declares a transport this server does not speak`);
      if (p.registryType === "mcpb") {
        assert.ok(p.fileSha256 === "TBD" || /^[0-9a-f]{64}$/.test(p.fileSha256),
          `${file} fileSha256 is neither TBD nor a sha256: ${p.fileSha256}`);
      }
    }
    if (file === "server.mcpb.json" || file === "server.json") {
      const remotes = JSON.parse(readFileSync(join(HERE, "remotes.json"), "utf8"));
      assert.deepEqual(j.remotes, remotes, `${file} remotes must equal remotes.json (hosted at /mcp/onboarding)`);
      assert.equal(remotes[0].url, "https://mcp.zovo.one/mcp/onboarding");
    } else if (file !== "server.onboarding.json") {
      assert.equal(j.remotes, undefined, `${file} is a stdio-only name and must not advertise a remote`);
    }
    assert.ok((j.description ?? "").length < 100, `${file} description is ${(j.description ?? "").length} chars; the registry 422s at 100`);
    assert.ok(!/[,.]\.$|,$/.test(j.description), `${file} description ends in a machine truncation`);
    assert.ok(!/—/.test(JSON.stringify(j)), `${file} carries an em dash`);
  }
  assert.ok(existsSync(join(HERE, "remotes.json")), "remotes.json is missing: this server has a hosted route in remote/src/index.ts");

  const names = MANIFESTS.map((f) => JSON.parse(readFileSync(join(HERE, f), "utf8")).name);
  // server.json and server.mcpb.json legitimately share the registry name; only the
  // third manifest (the app-specific one) carries a distinct name.
  assert.equal(new Set(names).size, 2, `registry names must differ: ${names.join(", ")}`);
  assert.equal(names[0], names[1], "server.json and server.mcpb.json share the registry name");
  assert.notEqual(names[2], names[0], "server.onboarding.json carries a distinct name");
  assert.deepEqual(names, [
    "io.github.theluckystrike/onboarding",
    "io.github.theluckystrike/onboarding",
    "io.github.theluckystrike/new-hire-onboarding-tasks",
  ]);

  execFileSync(process.execPath, [join(REPO, "scripts", "sync-versions.mjs"), "--check"], { encoding: "utf8" });
});

