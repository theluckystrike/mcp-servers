test("the estate lists this server everywhere a new server has to be registered", () => {
  const missing = [];
  const probe = (file, re, label) => {
    const p = join(REPO, file);
    if (!existsSync(p)) { missing.push(`${file} (file missing)`); return; }
    if (!re.test(readFileSync(p, "utf8"))) missing.push(`${file} (${label})`);
  };
  probe("scripts/build-mcpb.sh", /onboarding/, "build-mcpb.sh");
  probe("scripts/gen-spec.mjs", /onboarding/, "gen-spec.mjs");
  probe("scripts/validate.mjs", /onboarding/, "validate.mjs");
  probe("data/facts.json", /onboarding/, "facts.json");
  probe("data/tools.json", /onboarding/, "tools.json");
  probe("data/distribution.json", /onboarding/, "distribution.json");
  probe("README.md", /onboarding/, "README.md");
  probe("scripts/sync-mirrors.sh", /onboarding/, "sync-mirrors.sh");
  assert.deepEqual(missing, [], `estate registration gaps: ${missing.join("; ")}`);
});

