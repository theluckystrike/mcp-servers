test("the snapshot rule is real: a hire keeps its tasks when the template changes later", async (t) => {
  const { c } = open(t);
  await c.init();
  const hire = await seedHire(c, "Ada Lovelace", "engineer", "2099-01-01");
  await c.call("onboarding_template_apply", { hire: hire.id, tasks: TASKS });
  const before = await c.call("onboarding_progress", { hire: hire.id });
  const beforeBody = JSON.parse(before.text);

  // Change the template's tasks: rename one, add one, then bump the version.
  await c.call("onboarding_task_add", { hire: hire.id, text: "Unchanged hire task", owner: "it", due_offset: 9 });
  const after = await c.call("onboarding_progress", { hire: hire.id });
  const afterBody = JSON.parse(after.text);
  assert.equal(afterBody.hire.tasks, beforeBody.hire.tasks + 1, "editing the template never rewrites a hire already under way");
  assert.equal(afterBody.hire.template_version, beforeBody.hire.template_version, "the hire keeps the template version it was applied at");
});

