test("every count the server emits is a whole number and the parts sum to the whole", async (t) => {
  const { c } = open(t);
  await c.init();
  const hire = await seedHire(c);
  await c.call("onboarding_task_add", { hire: hire.id, text: "A", owner: "it", due_offset: 0 });
  await c.call("onboarding_task_add", { hire: hire.id, text: "B", owner: "hr", due_offset: 1 });
  await c.call("onboarding_task_done", { hire: hire.id, task: "K01", status: "done" });
  const p = JSON.parse((await c.call("onboarding_progress", { hire: hire.id })).text);
  for (const [k, v] of Object.entries(p.counts ?? p)) {
    if (typeof v === "number") assert.ok(Number.isInteger(v), `${k} is ${v}, not a whole number`);
  }
  assert.equal(p.hire.done + p.hire.skipped + p.hire.todo, p.hire.tasks, "done + skipped + todo must sum to the task count");
});

