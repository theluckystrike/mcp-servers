test("the snapshot rule is on disk: a run stores its own items, not a pointer to the purchase-requisition", async (t) => {
  const { box, c } = open(t);
  await c.init();
  const { purchaseRequisition } = await seed(c);
  await c.json("purchase-requisition_item_add", { purchaseRequisition, text: "A step added after the run started", required: true });
  const runs = JSON.parse(readFileSync(join(storeDir(box.dataHome), "runs.json"), "utf8"));
  const r = runs[0];
  assert.equal(r.items.length, 6, "the run's items are not its own copy");
  assert.equal(r.items.some((i) => /added after the run started/.test(i.text)), false);
  assert.equal(r.template_version, 7, "the run did not record the purchase-requisition version it copied");
  assert.deepEqual(Object.keys(r).sort(), [
    "created", "date", "history", "id", "items", "reference", "status",
    "template", "template_name", "template_version", "title", "updated",
  ]);
  assert.deepEqual(Object.keys(r.items[0]).sort(), ["at", "by", "id", "required", "section", "state", "text"]);
  // And no progress figure is stored: every count is derived on the call.
  const raw = readFileSync(join(storeDir(box.dataHome), "runs.json"), "utf8");
  for (const key of ["progress", "percent_answered", "pass_count", "answered", "ready_to_sign_off", "complete"]) {
    assert.equal(raw.includes(`"${key}"`), false, `${key} was stored; every count must be derived on the call`);
  }
});

