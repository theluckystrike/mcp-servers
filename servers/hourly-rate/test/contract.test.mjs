// Contract suite for hourly-rate. Mechanical assertions only.
// One version number across package.json, src/version.ts, serverInfo and both registry
// manifests; no remotes block anywhere (stdio-only); JSON-RPC-only stdout; description
// hygiene; and the arithmetic invariants of the rate formula.
import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { client, sandbox, cleanup, REPO } from "./_client.mjs";

const HERE = join(REPO, "servers", "hourly-rate");

function open(t) {
  const box = sandbox();
  const c = client({ dataHome: box.dataHome });
  t.after(() => { c.close(); cleanup(box.dir); });
  return { box, c };
}

test("the version is one number: package.json, src/version.ts, serverInfo and both manifests agree", async (t) => {
  const pkg = JSON.parse(readFileSync(join(HERE, "package.json"), "utf8"));
  assert.equal(pkg.name, "mcp-hourly-rate");
  assert.match(pkg.version, /^\d+\.\d+\.\d+$/);
  assert.ok(pkg.description.length < 100, `package description is ${pkg.description.length} chars`);
  const generated = readFileSync(join(HERE, "src", "version.ts"), "utf8");
  assert.match(generated, /GENERATED by scripts\/sync-versions\.mjs/);
  assert.match(generated, new RegExp(`export const VERSION = "${pkg.version.replace(/\./g, "\\.")}";`),
    "src/version.ts does not match package.json; run node scripts/sync-versions.mjs");
  const { c } = open(t);
  const info = await c.init();
  assert.equal(info.serverInfo.version, pkg.version);
  assert.equal(info.serverInfo.name, "mcp-hourly-rate");
  for (const file of ["server.json", "server.variant.json"]) {
    const j = JSON.parse(readFileSync(join(HERE, file), "utf8"));
    assert.equal(j.version, pkg.version, `${file} version`);
    assert.equal(j.remotes, undefined, `${file} is stdio-only and must not advertise a remote`);
    assert.ok((j.description ?? "").length < 100, `${file} description is ${(j.description ?? "").length} chars; the registry 422s at 100`);
    assert.ok(!/[,.]\.$|,$/.test(j.description), `${file} description ends in a machine truncation`);
  }
  const names = ["server.json", "server.variant.json"].map((f) => JSON.parse(readFileSync(join(HERE, f), "utf8")).name);
  assert.equal(new Set(names).size, 2, `registry names must differ: ${names.join(", ")}`);
});

test("stdout is JSON-RPC only and the three tools are listed with usable descriptions", async (t) => {
  const { c } = open(t);
  await c.init();
  for (const line of c.stdoutLines) assert.doesNotThrow(() => JSON.parse(line), "non-JSON on stdout");
  const tools = await c.tools();
  assert.deepEqual(tools.map((x) => x.name).sort(), ["break_even", "calculate_rate", "what_if"]);
  for (const tool of tools) {
    assert.ok(tool.description.length > 10 && tool.description.length <= 220, `${tool.name} description length ${tool.description.length}`);
    assert.doesNotMatch(tool.description, /^(Call this tool|Use this)\b/);
  }
});

test("calculate_rate: 60k income, 10k expenses, 25 h/wk, 46 weeks, 30% tax is 87.06", async (t) => {
  const { c } = open(t);
  await c.init();
  const r = await c.call("calculate_rate", {
    desired_annual_income: 60000, business_expenses: 10000,
    billable_hours_per_week: 25, weeks_per_year: 46, tax_rate_pct: 30,
  });
  assert.equal(r.isError, false, r.text);
  // (60000+10000)/(25*46)/0.7 = 70000/1150/0.7 = 87.0629...
  assert.match(r.text, /\$87\.06/);
  assert.match(r.text, /Billable hours per year: 1150/);
});

test("break_even: 12k expenses, 20 h/wk, 48 weeks, no tax is 12.50", async (t) => {
  const { c } = open(t);
  await c.init();
  const r = await c.call("break_even", { business_expenses: 12000, billable_hours_per_week: 20, weeks_per_year: 48 });
  assert.equal(r.isError, false, r.text);
  assert.match(r.text, /\$12\.50/);
});

test("what_if ranks scenarios highest first and refuses fewer than two", async (t) => {
  const { c } = open(t);
  await c.init();
  const r = await c.call("what_if", { scenarios: [
    { label: "lean", desired_annual_income: 50000, billable_hours_per_week: 25, business_expenses: 5000 },
    { label: "ambitious", desired_annual_income: 80000, billable_hours_per_week: 20, business_expenses: 15000 },
  ]});
  assert.equal(r.isError, false, r.text);
  const iLean = r.text.indexOf("lean:");
  const iAmb = r.text.indexOf("ambitious:");
  assert.ok(iAmb >= 0 && iLean >= 0);
  // ambitious costs more over fewer hours, so its rate is higher and it comes first
  assert.ok(iAmb < iLean, "highest rate must come first");
  const bad = await c.call("what_if", { scenarios: [{ label: "only", billable_hours_per_week: 10 }] });
  assert.equal(bad.isError, true);
});

test("hostile inputs are refused with a reason, nothing hangs", async (t) => {
  const { c } = open(t);
  await c.init();
  for (const args of [
    { billable_hours_per_week: 0 },
    { billable_hours_per_week: -5 },
    { billable_hours_per_week: 25, tax_rate_pct: 100 },
    { billable_hours_per_week: 25, weeks_per_year: 60 },
    { billable_hours_per_week: 25, desired_annual_income: -1 },
  ]) {
    const r = await c.call("calculate_rate", args);
    assert.equal(r.isError, true, `expected an error for ${JSON.stringify(args)}: ${r.text}`);
    assert.match(r.text, /Nothing was calculated/);
  }
});
