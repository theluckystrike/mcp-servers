test("every amount the server emits is an integer number of minor units", async (t) => {
  const { c } = open(t, { key: proKey() });
  await c.init();
  const opened = await c.json("float_open", FLOAT);
  for (const k of ["imprest_minor", "balance_minor"]) assert.ok(Number.isInteger(opened.opened[k]), k);
  for (const v of MONTH) await c.call("voucher_add", v);
  const rec = await c.json("reconcile", { counted_minor: COUNTED, date: COUNT_DATE });
  for (const k of ["expected_minor", "counted_minor", "difference_minor", "balance_after_minor"]) {
    assert.ok(Number.isInteger(rec[k]), `${k} is not an integer: ${rec[k]}`);
  }
  for (const v of rec.vouchers_reconciled) {
    assert.ok(Number.isInteger(v.amount_minor));
    assert.match(v.date, /^\d{4}-\d{2}-\d{2}$/);
  }
  const rep = await c.json("replenish_request", { date: "2026-04-01" });
  for (const k of ["balance_minor", "request_minor", "vouchers_total_minor", "cash_over_short_minor"]) {
    assert.ok(Number.isInteger(rep[k]), `${k} is not an integer: ${rep[k]}`);
  }
  for (const l of rep.journal) {
    assert.ok(Number.isInteger(l.debit) && Number.isInteger(l.credit), JSON.stringify(l));
    assert.ok(l.debit === 0 || l.credit === 0, `a line is both a debit and a credit: ${JSON.stringify(l)}`);
  }
  assert.equal(rep.journal.reduce((x, l) => x + l.debit - l.credit, 0), 0, "the journal does not balance");
});
