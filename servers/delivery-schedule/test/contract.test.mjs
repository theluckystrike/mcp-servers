test("the free tier is the documented one: open, add, move, get, list, delete and the late report are free", async (t) => {
  const { c } = open(t);
  await c.init();
  const id = await seed(c);
  for (const [tool, args] of [
    ["deliverable_add", { schedule: id, description: "Extra page", due_date: "2026-05-20", value_minor: 1000 }],
    ["deliverable_status", { schedule: id, deliverable: "D05", status: "delivered", date: "2026-05-19" }],
    ["deliverable_delete", { schedule: id, deliverable: "D04" }],
    ["delivery_schedule_get", { schedule: id, as_of: AS_OF_LATE }],
    ["delivery_schedule_list", {}],
    ["late_report", { as_of: AS_OF_LATE }],
    ["delivery_schedule_create", { reference: "Q-2026-0500", reference_date: "2026-04-01", client: "Harbour Cafe", title: "Second job" }],
    ["delivery_schedule_delete", { schedule: "Q-2026-0500" }],
  ]) {
    const r = await c.call(tool, args);
    assert.equal(r.isError, false, `${tool} was gated: ${r.text}`);
  }
  for (const [tool, args] of [
    ["delivery_schedule_document", { schedule: id }],
    ["milestone_payload", { schedule: id }],
  ]) {
    const r = await c.call(tool, args);
    assert.equal(r.isError, true, `${tool} answered on the free tier`);
    assert.match(r.text, /Pro is a one-time \$\d+ for this server/, tool);
    assert.match(r.text, /license_activate/, tool);
    // The conversion instrument: every gate link carries the tool that tripped it.
    assert.match(r.text, new RegExp(`src=${PRODUCT}\\.${tool}`), `${tool} gate link is untagged`);
    // And the shared cap sentence: no hand math, then the bundle link, on every gate.
    assert.match(r.text, /any total or journal composed outside them is an estimate/, `${tool} lacks the NO_HAND_MATH sentence`);
    assert.match(r.text, new RegExp(`Or all \\d+ servers for \\$\\d+: https://mcp\\.zovo\\.one/buy/bundle\\?src=${PRODUCT}\\.${tool}\\.bundle$`), `${tool} lacks the bundle sentence`);
  }
});

