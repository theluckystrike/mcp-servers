test("this server writes two files and no others, on any tool", async (t) => {
  const { box, c } = open(t, { key: proKey() });
  await c.init();
  const reg = await c.json("invoice_register", ACME);
  const id = reg.registered.id;
  await c.call("letter_render", { invoice: id });
  await c.call("letter_render", { invoice: id, format: "html" });
  await c.call("letter_sent", { invoice: id, stage: 1, sent: "2026-06-08" });
  await c.call("payment_record", { invoice: id, amount_minor: 50000, date: "2026-06-20" });
  await c.call("overdue_list", { on: "2026-07-01" });
  await c.call("aging_summary", { on: "2026-07-01" });
  await c.call("chase_today", { on: "2026-07-01" });
  await c.call("invoice_status", { invoice: id });
  const gone = await c.json("invoice_register", { ...ACME, reference: "INV-9999" });
  await c.call("invoice_delete", { invoice: gone.registered.id });

  const files = readdirSync(storeDir(box.dataHome)).filter((f) => !f.startsWith("."));
  assert.deepEqual(files.sort(), ["counter.json", "invoices.json"]);
  const siblings = readdirSync(join(box.dataHome, "mcp-servers")).sort();
  assert.deepEqual(siblings, ["dunning-letters", "profile"], `a sibling store was created: ${siblings.join(", ")}`);
  assert.deepEqual(readdirSync(join(box.dataHome, "mcp-servers", "profile")), ["business.json"],
    "this server wrote into the shared profile directory; it must only read business.json");
});

