test("the free-tier concurrent-chase cap carries the tagged link and the bundle, and nothing is written", async (t) => {
  const { box, c } = open(t);
  await c.init();
  for (let i = 1; i <= 3; i++) await c.json("invoice_register", { ...ACME, reference: `INV-${i}` });
  const r = await c.call("invoice_register", { ...ACME, reference: "INV-4" });
  assert.ok(r.isError, r.text);
  assert.match(r.text, /Pro is a one-time \$\d+ for this server/);
  assert.match(r.text, /license_activate/);
  assert.match(r.text, new RegExp(`src=${PRODUCT}\\.invoice_register`), "the gate link is untagged");
  assert.match(r.text, /buy\/bundle/);
  const invoices = JSON.parse(readFileSync(join(storeDir(box.dataHome), "invoices.json"), "utf8"));
  assert.equal(invoices.length, 3, "the refused fourth chase was written");
});

