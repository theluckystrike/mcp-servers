test("the free-tier draft cap carries the tagged link and the bundle, and nothing is written", async (t) => {
  const { box, c } = open(t);
  await c.init();
  for (let i = 1; i <= 10; i++) await c.json("sale_create", { ...SALE, item_description: `Lathe, unit ${i}` });
  const r = await c.call("sale_create", { ...SALE, item_description: "Lathe, unit 11" });
  assert.ok(r.isError, r.text);
  assert.match(r.text, /Pro is a one-time \$\d+ for this server/);
  assert.match(r.text, /license_activate/);
  assert.match(r.text, new RegExp(`src=${PRODUCT}\\.sale_create`), "the gate link is untagged");
  assert.match(r.text, /buy\/bundle/);
  const sales = JSON.parse(readFileSync(join(storeDir(box.dataHome), "sales.json"), "utf8"));
  assert.equal(sales.length, 10, "the refused eleventh draft was written");
});

test("the free-tier finalize cap also carries the tagged link and the bundle", async (t) => {
  const { c } = open(t);
  await c.init();
  for (let i = 1; i <= 5; i++) {
    const s = await c.json("sale_create", { ...SALE, item_description: `Compressor, unit ${i}` });
    assert.equal((await c.call("sale_finalize", { sale: s.recorded.id })).isError, false);
  }
  const s6 = await c.json("sale_create", { ...SALE, item_description: "Compressor, unit 6" });
  const r = await c.call("sale_finalize", { sale: s6.recorded.id });
  assert.ok(r.isError, r.text);
  assert.match(r.text, new RegExp(`src=${PRODUCT}\\.sale_finalize`));
  assert.match(r.text, /buy\/bundle/);
  assert.equal((await c.call("sale_render", { sale: s6.recorded.id, format: "markdown" })).isError, false, "rendering a draft stays free");
});

test("a finalized document is frozen and its number is never reissued", async (t) => {
  const { c } = open(t);
  await c.init();
  const s = await c.json("sale_create", SALE);
  assert.equal((await c.call("sale_finalize", { sale: s.recorded.id })).isError, false);
  const edit = await c.call("sale_update", { sale: s.recorded.id, price_minor: 1 });
  assert.ok(edit.isError, "sale_update edited a finalized document");
  const del = await c.call("sale_delete", { sale: s.recorded.id });
  assert.ok(del.isError, "sale_delete removed a finalized document without confirmation");
  const md = await c.call("sale_render", { sale: s.recorded.id, format: "markdown" });
  assert.equal(md.isError, false);
  assert.ok(!/DRAFT/.test(md.text), "the signing copy still carries the watermark");
});

