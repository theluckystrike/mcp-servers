test("this server writes its own directory and no sibling store, on any tool", async (t) => {
  const { box, c } = open(t, { key: proKey() });
  await c.init();
  const s = await c.json("sale_create", SALE);
  await c.call("sale_update", { sale: s.recorded.id, notes: "paid in cash" });
  await c.call("sale_render", { sale: s.recorded.id });
  await c.call("sale_finalize", { sale: s.recorded.id });
  await c.call("sale_render", { sale: s.recorded.id });
  await c.call("sale_list", {});
  await c.call("sale_summary", {});
  const gone = await c.json("sale_create", { ...SALE, item_description: "Filing cabinet" });
  await c.call("sale_delete", { sale: gone.recorded.id });

  const entries = readdirSync(storeDir(box.dataHome)).filter((f) => !f.startsWith("."));
  assert.deepEqual(entries.sort(), ["counter.json", "documents", "sales.json"]);
  const siblings = readdirSync(join(box.dataHome, "mcp-servers")).sort();
  assert.deepEqual(siblings, ["bill-of-sale", "profile"], `a sibling store was created: ${siblings.join(", ")}`);
  assert.deepEqual(readdirSync(join(box.dataHome, "mcp-servers", "profile")), ["business.json"],
    "this server wrote into the shared profile directory; it must only read business.json");
});

