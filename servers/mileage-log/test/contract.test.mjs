test("a trip earns the rate in force on its day, rounded half-up to the cent", async (t) => {
  const { c } = open(t);
  await c.init();
  await c.json("rate_set", RATE);
  const j = await c.json("trip_add", TRIP);
  const list = await c.json("trip_list", {});
  const priced = list.trips.find((x) => x.id === j.logged.id);
  assert.equal(priced.amount_cents, 875, `12.5 miles at 0.70 USD is 875 cents, got ${JSON.stringify(priced).slice(0, 200)}`);
  assert.equal(priced.rate_effective_from, "2026-01-01");
  const summary = await c.json("mileage_summary", { from_date: "2026-01-01", to_date: "2026-12-31" });
  assert.equal(summary.totals[0].amount_cents, 875);
  assert.equal(summary.totals[0].currency, "USD");
});

test("the free-tier monthly cap carries the tagged link, and another month still logs", async (t) => {
  const { box, c } = open(t);
  await c.init();
  for (let i = 1; i <= 20; i++) await c.json("trip_add", { ...TRIP, purpose: `Drive ${i}` });
  const r = await c.call("trip_add", { ...TRIP, purpose: "Drive 21" });
  assert.ok(r.isError, r.text);
  assert.match(r.text, /20 trips per calendar month/);
  assert.match(r.text, /Pro is a one-time \$\d+ for this server/);
  assert.match(r.text, /license_activate/);
  assert.match(r.text, new RegExp(`src=${PRODUCT}\\.trip_add`), "the gate link is untagged");
  assert.match(r.text, /buy\/bundle/);
  const trips = JSON.parse(readFileSync(join(storeDir(box.dataHome), "trips.json"), "utf8"));
  assert.equal(trips.length, 20, "the refused twenty-first trip was written");
  const april = await c.call("trip_add", { ...TRIP, date: "2026-04-01", purpose: "Next month" });
  assert.equal(april.isError, false, `a trip dated in another month was refused: ${april.text}`);
});

test("one rate per jurisdiction and category is free, overwriting it is free, the series is Pro", async (t) => {
  const { box, c } = open(t);
  await c.init();
  await c.json("rate_set", RATE);
  const second = await c.call("rate_set", { ...RATE, rate: 0.72, effective_from: "2027-01-01" });
  assert.ok(second.isError, "a second effective-dated rate was set on the free tier");
  assert.match(second.text, /Pro is a one-time \$\d+ for this server/);
  assert.match(second.text, new RegExp(`src=${PRODUCT}\\.rate_set`), "the gate link is untagged");
  const rates = JSON.parse(readFileSync(join(storeDir(box.dataHome), "rates.json"), "utf8"));
  assert.equal(rates.length, 1, "the refused second rate was written");
  const over = await c.json("rate_set", { ...RATE, rate: 0.71, effective_from: RATE.effective_from });
  assert.equal(over.replaced.rate, 0.7, "overwriting the same effective date is free and reports what it replaced");
});

