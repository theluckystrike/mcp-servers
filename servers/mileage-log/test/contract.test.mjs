test("the hosted registration is exactly one of two honest states", () => {
  // The hosted route for this server exists in remote/src/index.ts and the worker deploy is
  // pending (docs/HOSTED_LOOP35.md deploys; wave C wires). data/distribution.json must say
  // one of two things and nothing in between: the ONLY string that means live is the exact
  // published URL, because scripts/kpi.mjs counts hosted servers by string match.
  const dist = JSON.parse(readFileSync(join(REPO, "data", "distribution.json"), "utf8"));
  const hosted = String(dist.per_server["mileage-log"].hosted);
  const published = "published https://mcp.zovo.one/mcp/mileage-log";
  assert.ok(hosted === published || hosted.startsWith("none by design") || hosted.startsWith("pending deploy:"),
    `distribution.json per_server.mileage-log.hosted is neither the exact published string nor a pending note: ${hosted}`);
  // And the live-validation remote sweep covers this server, added by the wiring loop.
  const validate = readFileSync(join(REPO, "scripts", "validate.mjs"), "utf8");
  const remoteBlock = validate.slice(validate.indexOf("async function remote()"));
  assert.ok(remoteBlock.includes('"mileage-log"'), "scripts/validate.mjs remote() does not probe mileage-log");
});
