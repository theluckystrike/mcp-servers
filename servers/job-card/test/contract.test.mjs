test("the hosted registration is exactly one of two honest states", () => {
  // The hosted route for this server exists in remote/src/index.ts and the worker deploy is
  // pending (docs/HOSTED_LOOP34.md). data/distribution.json must say one of two things and
  // nothing in between: "none by design" is a narrative from before the route existed and is
  // now stale, but the ONLY string that means live is the exact published URL, because
  // scripts/kpi.mjs counts hosted servers by string match.
  const dist = JSON.parse(readFileSync(join(REPO, "data", "distribution.json"), "utf8"));
  const hosted = String(dist.per_server["job-card"].hosted);
  const published = "published https://mcp.zovo.one/mcp/job-card";
  assert.ok(hosted === published || hosted.startsWith("none by design") || hosted.startsWith("pending deploy:"),
    `distribution.json per_server.job-card.hosted is neither the exact published string nor a none-by-design note: ${hosted}`);
  // And the live-validation remote sweep covers this server, added by the hosting loop.
  const validate = readFileSync(join(REPO, "scripts", "validate.mjs"), "utf8");
  const remoteBlock = validate.slice(validate.indexOf("async function remote()"));
  assert.ok(remoteBlock.includes('"job-card"'), "scripts/validate.mjs remote() does not probe job-card");
});
