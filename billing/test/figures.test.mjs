// The honesty gate for round 4 content, and for the counts on the home page.
//
// Two defects motivated this file.
//
// 1. The home page stated the size of its own catalogue three different ways in one
//    document: "Thirty-one" in the h1, title and JSON-LD, "32 servers" in the validation
//    line, and "The 31 servers" over a table, while `ls servers/ | wc -l` returned 32. It is
//    the most retrieved page in the estate and nothing caught it, because no gate had ever
//    looked at a rendered page for a number.
// 2. billing/test/guide-figures.test.mjs holds one guide to one round file. The nine pages
//    added in round 4 quote rate limits, tool counts, prices and third-party findings, so
//    the same discipline is applied to all of them here: every figure has to be findable in
//    a file in this repository.
//
// billing/src/figures.js is generated by scripts/build-figures.mjs out of
// servers/*/src/index.ts, packages/mcp-license, remote/src/index.ts, servers/*/server.json
// and data/facts.json. The first test re-runs that generator in check mode, so a figure
// cannot be right in the page and stale against the source.

import test from "node:test";
import assert from "node:assert";
import { readFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
