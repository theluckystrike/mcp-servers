import worker, { SINGLE_PRODUCT_IDS, VALIDATION } from "../src/index.js";
import { GUIDES } from "../src/content.js";
import {
  LISTED_COUNT, LISTED_CHILD_COUNT, HOSTED_COUNT, SERVER_DIR_COUNT, VERSION,
} from "../src/figures.js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const read = (p) => readFileSync(join(ROOT, p), "utf8");

/** The nine pages written in round 4. Every figure on each has to resolve to a repo file. */
const R4_SLUGS = [
  "which-mcp-servers-work-by-pasting-a-url",
  "paid-mcp-servers-and-how-you-pay-for-one",
  "fill-a-quote-or-estimate-template-from-chat",
  "petty-cash-book-and-cash-ledger-mcp-servers",
  "currency-conversion-mcp-servers-compared",
  "zip-and-unzip-mcp-servers-compared",
  "delivery-schedule-and-work-order-documents-from-mcp",
  "will-an-mcp-server-email-the-invoice-to-my-client",
  "can-an-mcp-server-read-a-photo-of-a-receipt",
];

test("billing/src/figures.js is what the manifests currently say", () => {
  const out = execFileSync("node", [join(ROOT, "scripts/build-figures.mjs"), "--check"], { encoding: "utf8" });
  assert.match(out, /figures OK/);
});

test("the catalogue counts agree with each other", () => {
  assert.equal(SINGLE_PRODUCT_IDS.length, LISTED_CHILD_COUNT,
    `PRODUCTS sells ${SINGLE_PRODUCT_IDS.length} servers singly and ${LISTED_CHILD_COUNT} listed servers are not office-suite. One of them is wrong.`);
  assert.ok(HOSTED_COUNT <= LISTED_COUNT, "more hosted endpoints than listed servers");
  assert.ok(SERVER_DIR_COUNT >= LISTED_COUNT,
    "a listed server has no source directory, which cannot happen");
  assert.equal(VALIDATION.servers, LISTED_COUNT,
    `the home page claims ${VALIDATION.pass} of ${VALIDATION.total} checks across ${VALIDATION.servers} servers while the site lists ${LISTED_COUNT}. Re-run validation, then update VALIDATION in billing/src/index.js.`);
});

test("no count of servers on the home page is typed, spelled out, or wrong", async () => {
  const res = await worker.fetch(new Request("https://mcp.zovo.one/"), {}, { waitUntil() {} });
  const html = await res.text();

  // A machine reader gets nothing from "Thirty-one" that it does not get from 31, and a
  // spelled-out count is how the old defect hid: it did not look like the numerals it
  // contradicted. No English number word may sit in front of "servers" on this page.
  const spelled = [...html.matchAll(/\b(Twenty|Thirty|Forty|Fifty)(?:-[a-z]+)?\s+(?:local-first\s+)?(?:MCP\s+)?servers/g)].map((m) => m[0]);
  assert.deepEqual(spelled, [], `the home page spells out a server count: ${spelled.join(", ")}`);

  // Every numeral immediately in front of "servers" has to be a count this repository can
  // derive. 32 is what the site lists, 31 is what office-suite spawns and what is sold
  // singly, 30 is what answers at a URL.
  const allowed = new Set([LISTED_COUNT, LISTED_CHILD_COUNT, HOSTED_COUNT]);
  const found = [...html.matchAll(/\b(\d+)\s+(?:local-first\s+)?(?:MCP\s+)?servers/g)].map((m) => Number(m[1]));
  assert.ok(found.length > 0, "the home page states no server count at all, which means this gate is not looking at the page");
  const wrong = found.filter((n) => !allowed.has(n));
  assert.deepEqual(wrong, [], `the home page states a server count nothing in the repo derives: ${wrong.join(", ")}. Derived counts are ${[...allowed].join(", ")}.`);
});

test("the home page names servers and gives a URL rather than deferring", async () => {
  const res = await worker.fetch(new Request("https://mcp.zovo.one/"), {}, { waitUntil() {} });
  const html = await res.text();
  // The blind recommendation run retrieved this page twice and cited it neither time,
  // describing it as a generic listing page. A page an assistant can answer from has to
  // carry the name, the one-line description and the exact URL in the HTML, not behind a
  // link. One paste-in URL per hosted server, and none of them the bare form that returns
  // 401 on tools/call.
  const pasteUrls = html.match(/https:\/\/mcp\.zovo\.one\/mcp\/[a-z-]+\/t\/&lt;token&gt;/g) || [];
  assert.equal(pasteUrls.length, HOSTED_COUNT,
    `the home page prints ${pasteUrls.length} paste-in URLs for ${HOSTED_COUNT} hosted servers`);
  assert.match(html, /curl -X POST https:\/\/mcp\.zovo\.one\/mcp\/token/,
    "the home page does not say how to get the token its URLs need");
});

