/**
 * Files a round 4 figure may come from. figures.js carries the derived counts, limits and
 * prices; facts.json carries the per-server free tiers it is built from; the two docs carry
 * the third-party measurements the pages attribute rather than assert.
 */
const SOURCES = [
  "billing/src/figures.js",
  "data/facts.json",
  "docs/BLIND_RECOMMENDATION_R1.md",
  "docs/CONTENT_R3.md",
];

const haystack = SOURCES.map(read).join("\n").replace(/,(?=\d)/g, "");

/**
 * Figures that are correct but that the boundary-anchored match below cannot see, each with
 * the reason. Keep this list short and keep the reason on the line.
 */
const EXPLAINED = new Map([
  // VERSION is "0.21.0" in figures.js. Splitting a three-part version yields "0.21", which
  // the (?!\.\d) lookahead then refuses against its own source.
  ["0.21", `VERSION is ${VERSION} in billing/src/figures.js`],
]);

function figures(text) {
  // <pre> blocks are code, and HUMANIZE.md exempts code. They also carry hex tokens whose
  // digits are not figures about anything.
  const plain = text.replace(/<pre>[\s\S]*?<\/pre>/g, " ").replace(/<[^>]+>/g, " ");
  return [...new Set((plain.match(/\d[\d,]*(?:\.\d+)?/g) || []).map((n) => n.replace(/,/g, "")))];
}

test("every round 4 page exists", () => {
  for (const slug of R4_SLUGS) assert.ok(GUIDES[slug], `${slug} is not a live guide`);
});

for (const slug of R4_SLUGS) {
  test(`every figure on /guides/${slug} comes from a file in this repository`, () => {
    const g = GUIDES[slug];
    const text = [g.title, g.description, g.html, ...g.faq.flatMap((f) => [f.q, f.a])].join("\n");
    const missing = [];
    for (const n of figures(text)) {
      if (EXPLAINED.has(n)) continue;
      const re = new RegExp(`(?<!\\d)(?<!\\d\\.)${n.replace(".", "\\.")}(?!\\d)(?!\\.\\d)`);
      if (!re.test(haystack)) missing.push(n);
    }
    assert.deepEqual(missing, [], `figures on ${slug} that no source file carries: ${missing.join(", ")}. Sources searched: ${SOURCES.join(", ")}.`);
  });
}

test("every round 4 page states what it cannot do", () => {
  // The limitation section is the reason these pages are citable rather than promotional.
  // A page that loses it has lost the thing that made it worth writing.
  for (const slug of R4_SLUGS) {
    const h = GUIDES[slug].html;
    assert.match(h, /<h2>[^<]*cannot[^<]*<\/h2>|<h2>[^<]*limits[^<]*<\/h2>|<h2>[^<]*honest limits[^<]*<\/h2>/i,
      `${slug} has no section saying what the thing cannot do`);
  }
});

test("every round 4 page carries a paste-in URL or says why it cannot", () => {
  for (const slug of R4_SLUGS) {
    const h = GUIDES[slug].html;
    const hasUrl = /https:\/\/mcp\.zovo\.one\/mcp\/[a-z-]+\/t\/&lt;token&gt;/.test(h);
    const saysWhy = /no hosted endpoint|No URL|no URL/.test(h);
    assert.ok(hasUrl || saysWhy, `${slug} gives neither a paste-in URL nor a reason there is none`);
  }
});

// ---------------------------------------------------------------------------
// Spelled-out counts.
// ---------------------------------------------------------------------------
//
// Numerals were not enough. The home page contradicted itself in numerals AND in words,
// and the word was the copy nobody grepped for: "Thirty-one" in an h1 while the validation
// line two paragraphs down said 32. The same defect put "the nineteen-server bundle for
// $39" on every generated product page for months, which is the most linked surface here,
// and "twelve MCP servers" on the /setup index while it listed 31.
//
// So: a spelled-out number in front of "server" is banned on the surfaces this repository
// writes, unless it names a specific measured run or a specific subset. Those exceptions
// are listed with their reason, and a new one has to be argued for in this file rather
// than typed into a page.

/** Exact phrases allowed to spell a count out, and why each one is not a catalogue claim. */
const SPELLED_OK = [
  // A dated measurement of the bundle as it was on 2026-09-04. Rewriting it would falsify
  // the measurement rather than fix a stale number.
  "nineteen-server build",
  // Pinned to data/user_value_r27.json, which billing/test/guide-figures.test.mjs enforces.
  "twenty-four servers",
  // The number of servers used in one worked run, and the number a client handles at once.
  "four servers",
  // The sibling servers the cash book reads, not the catalogue.
  "six servers",
  // A count inside a sample of the public registry, not of this catalogue.
  "nine servers",
];

const SPELLED = /\b(four|five|six|seven|eight|nine|ten|eleven|twelve|thirteen|fourteen|fifteen|sixteen|seventeen|eighteen|nineteen|twenty|thirty|forty|fifty)(-(?:one|two|three|four|five|six|seven|eight|nine))?[ -](server|MCP server)s?\b/gi;

function spelledOffenders(text) {
  const out = [];
  for (const m of text.matchAll(SPELLED)) {
    const phrase = m[0].toLowerCase().replace(/\s+/g, " ");
    if (SPELLED_OK.some((ok) => phrase.startsWith(ok) || ok.startsWith(phrase))) continue;
    out.push(`${phrase} (in "...${text.slice(Math.max(0, m.index - 50), m.index + m[0].length + 20).replace(/\s+/g, " ")}...")`);
  }
  return out;
}

test("no guide spells out a count of servers", () => {
  const bad = [];
  for (const [slug, g] of Object.entries(GUIDES)) {
    const text = [g.title, g.description, g.html, ...g.faq.flatMap((f) => [f.q, f.a])].join("\n");
    for (const hit of spelledOffenders(text)) bad.push(`/guides/${slug}: ${hit}`);
  }
  assert.deepEqual(bad, [], bad.join("\n"));
});

test("no rendered page spells out a count of servers", async () => {
  const env = {};
  const ctx = { waitUntil() {} };
  const bad = [];
  for (const path of ["/", "/bundle", "/setup", "/setup/cursor", "/guides", "/llms.txt", "/s/invoice", "/s/office-suite"]) {
    const html = await (await worker.fetch(new Request(`https://mcp.zovo.one${path}`), env, ctx)).text();
    for (const hit of spelledOffenders(html)) bad.push(`${path}: ${hit}`);
  }
  assert.deepEqual(bad, [], bad.join("\n"));
});
