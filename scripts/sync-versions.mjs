#!/usr/bin/env node
// Generate servers/<name>/src/version.ts from that server's package.json version.
// The version a server announces in serverInfo must equal the version every catalogue
// (npm package.json, .mcpb manifest, registry entry) reports. A string literal in
// index.ts drifts silently across releases, and package.json cannot be read at runtime
// from the vendored Workers bundle (no filesystem), so the value is generated into a
// source file that both tsc and remote/build-vendor.mjs compile.
// Run: node scripts/sync-versions.mjs [--check]
import { readFileSync, writeFileSync, existsSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SERVERS_DIR = join(ROOT, "servers");
const check = process.argv.includes("--check");

const body = (v) =>
  "// GENERATED by scripts/sync-versions.mjs from this package's package.json. Do not edit.\n" +
  `export const VERSION = ${JSON.stringify(v)};\n`;

let changed = 0;
let stale = [];
for (const name of readdirSync(SERVERS_DIR).sort()) {
  const dir = join(SERVERS_DIR, name);
  const pkgPath = join(dir, "package.json");
  const srcPath = join(dir, "src", "version.ts");
  if (!existsSync(pkgPath) || !existsSync(join(dir, "src"))) continue;
  const version = JSON.parse(readFileSync(pkgPath, "utf8")).version;
  if (!version) throw new Error(`no version in ${pkgPath}`);
  const want = body(version);
  const have = existsSync(srcPath) ? readFileSync(srcPath, "utf8") : null;
  if (have === want) continue;
  stale.push(`${name} -> ${version}`);
  if (!check) { writeFileSync(srcPath, want); changed++; }
}

if (check && stale.length) {
  console.error(`sync-versions: stale version.ts: ${stale.join(", ")}`);
  process.exit(1);
}
console.log(`sync-versions: ${changed} file(s) written${changed ? ` (${stale.join(", ")})` : ""}`);
