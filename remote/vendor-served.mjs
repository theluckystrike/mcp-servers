// Vendoring for the twelve serve()-scaffold servers (see A3 sprint 2026-11-06).
// Mechanical: copy src files, retarget the _shared.js import at the hosted serve shim,
// and wrap the module body in `export function createServer()` so state (LEDGER etc.)
// is per-request and the endpoint gets a fresh McpServer per connection, exactly like
// every other vendored server. Run: node remote/vendor-served.mjs
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "remote", "src", "vendor");

const SERVERS = [
  "budget", "hourly-rate", "loan-calculator", "payroll", "pomodoro",
  "receipts", "stripe-billing", "tax-calc",
];

for (const name of SERVERS) {
  const src = join(ROOT, "servers", name, "src");
  const dst = join(OUT, name);
  mkdirSync(dst, { recursive: true });
  for (const f of readdirSync(src)) {
    if (f === "_shared.js") continue; // replaced by remote/src/shims/serve.ts
    let text = readFileSync(join(src, f), "utf8");
    // Retarget the shared scaffold at the hosted shim (serve + money both live there).
    text = text.replace(/['"]\.\/_shared\.js['"]/g, '"../../shims/serve.js"');
    if (/^index\.(ts|js)$/.test(f)) {
      // Wrap the whole module body in createServer() so module-scope state
      // (LEDGER, counters, ...) is re-created per request, and return the
      // single top-level serve(...) call's McpServer.
      const lines = text.split("\n").filter((l) => !l.startsWith("#!"));
      // Hoist imports to module scope; ES imports are illegal inside a function body.
      const imports = lines.filter((l) => /^import .*$/.test(l.trim()) && !l.trim().startsWith("import type"));
      const bodyLines = lines.filter((l) => !/^import (?!type)/.test(l));
      const callIdx = lines.findIndex((l) => /^serve\(/.test(l));
      if (callIdx === -1) throw new Error(`${name}: no top-level serve() call found`);
      lines[callIdx] = "return " + lines[callIdx];
      const body = lines
        .map((l) => (l.trim() === "" ? l : "  " + l))
        .join("\n");
      text = `// GENERATED by remote/vendor-served.mjs from servers/${name}/src/index.${f.split(".").pop()}. Do not edit.\nimport { serve } from "../../shims/serve.js";\n\nexport function createServer() {\n${body}\n}\n`;
    }
    writeFileSync(join(dst, f), text);
  }
  console.log("vendored", name);
}
