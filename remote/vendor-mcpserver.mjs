// Vendors the four McpServer-scaffold servers that remote/vendor-served.mjs skipped
// (they have no top-level serve() call: new McpServer + StdioServerTransport instead).
// Follows the same convention as build-vendor.mjs output: retargeted shims, body wrapped
// in export function createServer() so per-request state is fresh, returns the McpServer.
// Run: node remote/vendor-mcpserver.mjs
import { readFileSync, writeFileSync, mkdirSync, readdirSync, copyFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "remote", "src", "vendor");

const SERVERS = [
  "duplicate-invoice-check",
  "office-suite",
  "supplier-statement-check",
  "three-way-match",
];

const SHIM = {
  "@theluckystrike/mcp-license": "../../shims/license.js",
  "node:fs": "../../shims/fs.js",
  "node:fs/promises": "../../shims/fs.js",
  "node:os": "../../shims/os.js",
};

for (const name of SERVERS) {
  const src = join(ROOT, "servers", name, "src");
  const dst = join(OUT, name);
  mkdirSync(dst, { recursive: true });

  for (const f of readdirSync(src)) {
    if (!/\.(ts|js)$/.test(f) || f === "_shared.js") continue;
    const raw = readFileSync(join(src, f), "utf8");

    if (!/^index\.(ts|js)$/.test(f)) {
      // Support modules: same retargeting, no wrapping.
      let t = raw;
      for (const [from, to] of Object.entries(SHIM)) {
        t = t.replace(new RegExp(`from (['"])${from.replace(/[/]/g, "\\/")}\\1`, "g"), `from "${to}"`);
      }
      writeFileSync(join(dst, f), t);
      continue;
    }

    const lines = raw.split("\n").filter((l) => !l.startsWith("#!"));
    const imports = [];
    const body = [];
    for (const l of lines) {
      const m = l.match(/^\s*import\s.*?from\s+(['"])([^'"]+)\1;?\s*$/);
      if (m) {
        let spec = m[2];
        if (spec.endsWith("/server/stdio.js")) continue; // hosted transport is the Worker
        if (SHIM[spec]) spec = SHIM[spec];
        imports.push(l.replace(m[1] + m[2] + m[1], JSON.stringify(spec)));
        continue;
      }
      body.push(l);
    }

    // Drop the stdio connect call (last statement) and return the server instead.
    const ci = body.findIndex((l) => /^server\.connect\(/.test(l.trim()));
    const end = ci === -1 ? body.length : ci;
    const trimmed = body.slice(0, end).join("\n").replace(/\s+$/, "");

    const text =
      `// GENERATED by remote/vendor-mcpserver.mjs from servers/${name}/src/index.${f.split(".").pop()}. Do not edit.\n` +
      imports.join("\n") +
      `\n\nexport function createServer() {\n` +
      trimmed
        .split("\n")
        .map((l) => (l.trim() === "" ? "" : "  " + l))
        .join("\n") +
      `\n  return server;\n}\n`;
    writeFileSync(join(dst, f), text);
  }
  console.log("vendored", name);
}
